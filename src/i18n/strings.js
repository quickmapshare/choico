export function t(lang, khoa, ...tham) {
  const ban = CHU[lang] ?? CHU.vi;
  const gia = ban[khoa] ?? CHU.vi[khoa];
  return typeof gia === "function" ? gia(...tham) : gia;
}

// Đường dẫn theo ngôn ngữ: vi ở gốc, en ở /en/
export function duongDan(lang, phan = "") {
  const tien = lang === "en" ? "/en" : "";
  return `${tien}${phan}`.replace(/\/\//g, "/") || "/";
}
